"use client";

import { useEffect, useState } from "react";
import { apiUrl, designKey, exportsForDesign, renderDrawing } from "../lib/api";
import { fmt, fmtJpy, fmtPercent, formatMetric, keyMetrics, metricLabel } from "../lib/format";
import type { Candidate, Design, ExportInfo, Tier } from "../lib/types";

interface CandidateCardsProps {
  candidates: Candidate[];
  tier: Tier | null;
  selectedId: string | null;
  onSelect: (id: string) => void;
  /** Download maps from export_report / render_drawing tool results (see lib/api.ts). */
  exports?: ExportInfo[];
}

/** Labels for the keys of an ExportInfo.download map. */
const DOWNLOAD_LABEL: Record<string, string> = {
  svg: "側面図 SVG",
  report: "レポート .md",
  bom: "部品表 .csv",
  json: "レポート .json",
};
const DOWNLOAD_ORDER: readonly string[] = ["svg", "report", "bom", "json"];

/**
 * Inline SVG side view: POST /artifacts/render for the design, then GET the SVG. The SVG is
 * generated by our own backend (rocketwright/drawing.py), which is why innerHTML is acceptable.
 * The fetch runs only once the <details> is opened and keys on the stable design string, so
 * re-renders with an equal design do not refetch.
 */
function SideView({ design }: { design: Design }) {
  const key = designKey(design);
  const [open, setOpen] = useState<boolean>(false);
  const [svg, setSvg] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => {
    if (!open) return undefined;
    const controller = new AbortController();
    setSvg(null);
    setError(null);
    const parsed = JSON.parse(key) as Design;
    renderDrawing(parsed, controller.signal)
      .then((text) => {
        if (!controller.signal.aborted) setSvg(text);
      })
      .catch((err: unknown) => {
        if (controller.signal.aborted) return;
        setError(err instanceof Error ? err.message : String(err));
      });
    return () => controller.abort();
  }, [key, open]);
  return (
    <details
      className="side-view"
      onClick={(e) => e.stopPropagation()}
      onToggle={(e) => setOpen((e.currentTarget as HTMLDetailsElement).open)}
    >
      <summary className="card-section">側面図</summary>
      {!open ? null : error !== null ? (
        <div className="fail-reasons">側面図を取得できませんでした: {error}</div>
      ) : svg === null ? (
        <div className="muted">描画中...</div>
      ) : (
        <div className="drawing-svg" dangerouslySetInnerHTML={{ __html: svg }} />
      )}
    </details>
  );
}

/** Download links for one or more export_report / render_drawing results. */
function DownloadLinks({ exports }: { exports: ExportInfo[] }) {
  if (exports.length === 0) return null;
  return (
    <div className="card-downloads" style={{ marginTop: 6 }} onClick={(e) => e.stopPropagation()}>
      <div className="card-section">ダウンロード</div>
      {exports.map((e) => (
        <div key={`${e.source_id}:${e.id}`} style={{ display: "flex", flexWrap: "wrap", gap: 8 }}>
          <span className="muted mono">{e.id}</span>
          {DOWNLOAD_ORDER.filter((k) => k in e.download).map((k) => (
            <a key={k} href={apiUrl(e.download[k])} target="_blank" rel="noreferrer" download>
              {DOWNLOAD_LABEL[k] ?? k}
            </a>
          ))}
          {Object.keys(e.download)
            .filter((k) => !DOWNLOAD_ORDER.includes(k))
            .map((k) => (
              <a key={k} href={apiUrl(e.download[k])} target="_blank" rel="noreferrer" download>
                {k}
              </a>
            ))}
        </div>
      ))}
    </div>
  );
}

/** Design variables, rendered per design family (discriminated on design.tier). */
function DesignVars({ design }: { design: Design }) {
  if (design.tier === "commercial" || design.tier === "heavy") {
    return (
      <>
        <div className="card-section">段構成</div>
        <table className="table">
          <thead>
            <tr>
              <th>段</th>
              <th>エンジン</th>
              <th className="num">基数</th>
              <th className="num">推進剤</th>
              <th className="num">構造比</th>
            </tr>
          </thead>
          <tbody>
            {design.stages.map((s, i) => (
              <tr key={i}>
                <td>{i + 1}</td>
                <td className="mono">{s.engine_id}</td>
                <td className="num">{s.engine_count}</td>
                <td className="num">{fmt(s.propellant_mass_kg, 0)} kg</td>
                <td className="num">{fmtPercent(s.structural_fraction)}</td>
              </tr>
            ))}
          </tbody>
        </table>
        <dl className="kv" style={{ marginTop: 6 }}>
          {design.boosters.length > 0 && (
            <>
              <dt>ブースタ</dt>
              <dd>{design.boosters.map((b) => `${b.booster_id} x${b.count}`).join(", ")}</dd>
            </>
          )}
          <dt>フェアリング</dt>
          <dd>{fmt(design.fairing_mass_kg, 0)} kg</dd>
          <dt>積載質量</dt>
          <dd>{fmt(design.payload_mass_kg, 1)} kg</dd>
          <dt>ピッチ開始 / 角度</dt>
          <dd>
            {fmt(design.pitch_start_s, 1)} s / {fmt(design.initial_pitch_deg, 1)}°
          </dd>
        </dl>
      </>
    );
  }
  if (design.tier === "amateur") {
    const f = design.fins;
    return (
      <dl className="kv">
        <dt>機体 直径 / 全長</dt>
        <dd>
          {fmt(design.body_diameter_m * 1000, 0)} mm / {fmt(design.body_length_m, 2)} m
        </dd>
        <dt>ノーズ</dt>
        <dd>
          {design.nose_shape} {fmt(design.nose_length_m * 1000, 0)} mm
        </dd>
        <dt>フィン</dt>
        <dd>
          {f.count} 枚, 翼根 {fmt(f.root_chord_m * 1000, 0)} / 翼端 {fmt(f.tip_chord_m * 1000, 0)} / スパン{" "}
          {fmt(f.span_m * 1000, 0)} mm
        </dd>
        <dt>モーター</dt>
        <dd>{design.motor_id}</dd>
        <dt>乾燥質量 / 積載</dt>
        <dd>
          {fmt(design.dry_mass_kg, 2)} / {fmt(design.payload_mass_kg, 2)} kg
        </dd>
        <dt>パラシュート</dt>
        <dd>
          φ{fmt(design.parachute_diameter_m, 2)} m, 遅延 {fmt(design.deploy_delay_s, 1)} s
        </dd>
      </dl>
    );
  }
  if (design.tier !== "bottle") return null;
  return (
    <dl className="kv">
      <dt>ボトル容量</dt>
      <dd>{fmt(design.bottle_volume_m3 * 1000, 2)} L</dd>
      <dt>水の充填率</dt>
      <dd>{fmtPercent(design.water_fill_frac)}</dd>
      <dt>初期ゲージ圧</dt>
      <dd>{fmt(design.initial_gauge_pressure_pa / 1000, 0)} kPa</dd>
      <dt>ノズル径</dt>
      <dd>{fmt(design.nozzle_diameter_m * 1000, 1)} mm</dd>
      <dt>乾燥質量 / 積載</dt>
      <dd>
        {fmt(design.dry_mass_kg, 3)} / {fmt(design.payload_mass_kg, 3)} kg
      </dd>
      <dt>羽根 / パラシュート</dt>
      <dd>
        {design.has_fins ? "あり" : "なし"} /{" "}
        {design.has_parachute
          ? `あり${design.parachute_diameter_m !== null ? ` φ${fmt(design.parachute_diameter_m, 2)} m` : ""}`
          : "なし"}
      </dd>
    </dl>
  );
}

export default function CandidateCards({
  candidates,
  tier,
  selectedId,
  onSelect,
  exports = [],
}: CandidateCardsProps) {
  const specs = keyMetrics(tier);
  const keySet = new Set(specs.map((s) => s.key));
  // Exports whose design matches no card are listed once under the cards.
  const cardKeys = new Set(candidates.map((c) => designKey(c.design)));
  const unmatched = exports.filter((e) => e.design === null || !cardKeys.has(designKey(e.design)));
  return (
    <div className="panel">
      <div className="panel-header">
        <h2 className="panel-title">設計案</h2>
        <span className="muted">{candidates.length} 件</span>
      </div>
      {candidates.length === 0 ? (
        <div className="empty">合格した設計案がここにカードで並びます</div>
      ) : (
        <div className="cards">
          {candidates.map((c, i) => {
            const selected = c.source_id === selectedId;
            const others = Object.entries(c.metrics).filter(([k]) => !keySet.has(k));
            return (
              <div
                key={c.source_id}
                className={`card${selected ? " card-selected" : ""}`}
                onClick={() => onSelect(c.source_id)}
                role="button"
                tabIndex={0}
                onKeyDown={(e) => {
                  if (e.key === "Enter" || e.key === " ") onSelect(c.source_id);
                }}
              >
                <div className="card-header">
                  <span className="card-title">
                    案 {i + 1} <small className="muted mono">{c.source_id}</small>
                  </span>
                  <span>
                    {c.inFinal && <span className="chip chip-muted">最終</span>}{" "}
                    <span className={`chip ${c.passed ? "chip-ok" : "chip-bad"}`}>
                      {c.passed ? "合格" : "不合格"}
                    </span>
                  </span>
                </div>
                <DesignVars design={c.design} />
                <div className="card-section">主要指標</div>
                <dl className="kv">
                  {specs.map((s) => {
                    const v = c.metrics[s.key];
                    return v === undefined ? null : (
                      <Metric key={s.key} label={s.label} value={s.format(v)} />
                    );
                  })}
                  <dt>費用</dt>
                  <dd>{fmtJpy(c.cost_jpy)}</dd>
                  {c.success_rate !== null && (
                    <>
                      <dt>成功率</dt>
                      <dd>{fmtPercent(c.success_rate)}</dd>
                    </>
                  )}
                </dl>
                {others.length > 0 && (
                  <details>
                    <summary className="card-section">その他の指標 ({others.length})</summary>
                    <dl className="kv">
                      {others.map(([k, v]) => (
                        <Metric key={k} label={metricLabel(k)} value={formatMetric(k, v)} />
                      ))}
                    </dl>
                  </details>
                )}
                {c.failure_reasons.length > 0 && (
                  <div className="fail-reasons" style={{ marginTop: 6 }}>
                    {c.failure_reasons.join(" / ")}
                  </div>
                )}
                {c.explanation && <div className="card-explanation">{c.explanation}</div>}
                <SideView design={c.design} />
                <DownloadLinks exports={exportsForDesign(exports, c.design)} />
              </div>
            );
          })}
        </div>
      )}
      {unmatched.length > 0 && (
        <div style={{ marginTop: 10 }}>
          <DownloadLinks exports={unmatched} />
        </div>
      )}
    </div>
  );
}

function Metric({ label, value }: { label: string; value: string }) {
  return (
    <>
      <dt>{label}</dt>
      <dd>{value}</dd>
    </>
  );
}
