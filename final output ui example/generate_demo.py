"""Regenerate the fixed UI fixture from the existing, offline amateur scenario."""

import json
import sys
from pathlib import Path

DESTINATION = Path(__file__).resolve().parent
sys.path.insert(0, str(DESTINATION.parent))

from pydantic import TypeAdapter  # noqa: E402

from rocketwright.agent.fake_client import DEMO_DESIGNS, DEMO_REQUIREMENTS  # noqa: E402
from rocketwright.agent.tools import execute_tool  # noqa: E402
from rocketwright.drawing import render_side_view_svg  # noqa: E402
from rocketwright.report import export_bom_csv, export_report_markdown  # noqa: E402
from rocketwright.schema import Design, Requirement, SimResult  # noqa: E402


def main() -> None:
    requirement = Requirement.model_validate(DEMO_REQUIREMENTS["amateur"])
    environment = {
        "launch_latitude_deg": 36.0,
        "launch_altitude_m": 300,
        "wind_speed_mps": 3.0,
        "wind_direction_deg": 270,
    }
    candidates = []
    for index, raw in enumerate(DEMO_DESIGNS["amateur"][1:]):
        label = f"案 {'AB'[index]}"
        result = execute_tool(
            "simulate_design",
            {"design": raw, "requirement": requirement.model_dump(mode="json"),
             "env": environment, "seed": 42},
            f"ui_demo_amateur_{index + 1}",
        )
        if "error" in result:
            raise RuntimeError(result["error"])
        design = TypeAdapter(Design).validate_python(raw)
        simulation = SimResult.model_validate(result)
        candidates.append({
            "label": label,
            "design": raw,
            "result": result,
            "drawing": render_side_view_svg(design, width_px=1200),
            "csv": export_bom_csv(design),
            "markdown": export_report_markdown(design, simulation, requirement=requirement),
        })
    payload = {"seed": 42, "environment": environment,
               "requirement": requirement.model_dump(mode="json"), "candidates": candidates}
    (DESTINATION / "demo-data.js").write_text(
        "// Fixed offline scenario; generated by generate_demo.py.\n"
        "window.ROCKET_DEMO = " + json.dumps(payload, ensure_ascii=False, allow_nan=False)
        + ";\n", encoding="utf-8",
    )
    for candidate in candidates:
        result = candidate["result"]
        print(candidate["label"], result["source_id"], result["success"],
              round(result["metrics"]["apogee_m"], 2), result["cost_jpy"])


if __name__ == "__main__":
    main()
