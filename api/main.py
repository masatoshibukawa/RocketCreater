"""FastAPI entry point. POST /design streams agent progress as server-sent events."""

from __future__ import annotations

from collections.abc import AsyncIterator

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import Response, StreamingResponse
from pydantic import BaseModel, Field

from rocketwright import __version__
from rocketwright.agent.loop import run_design_loop
from rocketwright.agent.store import DEFAULT_STORE, MEDIA_TYPES, store_drawing
from rocketwright.schema import Design, Env

CORS_ORIGINS = ["http://localhost:3000", "http://127.0.0.1:3000"]

app = FastAPI(title="RocketWright", version=__version__)
app.add_middleware(
    CORSMiddleware,
    allow_origins=CORS_ORIGINS,
    allow_methods=["*"],
    allow_headers=["*"],
)


class DesignRequest(BaseModel):
    text: str = Field(min_length=1, max_length=4000)
    seed: int | None = None
    env: Env | None = None


@app.get("/")
def root() -> dict[str, str]:
    """Orientation for anyone who opens the API port in a browser: the UI lives elsewhere."""
    return {
        "name": "RocketWright API",
        "version": __version__,
        "ui": "run `cd web && npm run dev` and open http://localhost:3000 (Node >= 18.18)",
        "docs": "/docs",
        "health": "/health",
        "design": "POST /design {text, seed?, env?} -> text/event-stream",
    }


@app.get("/health")
def health() -> dict[str, str]:
    return {"status": "ok", "version": __version__}


async def _sse(request: DesignRequest) -> AsyncIterator[str]:
    # `run_design_loop` is looked up at call time so tests can monkeypatch it on this module.
    async for event in run_design_loop(request.text, seed=request.seed, env=request.env):
        yield f"event: {event.type}\ndata: {event.model_dump_json()}\n\n"


@app.post("/design")
async def design(request: DesignRequest) -> StreamingResponse:
    return StreamingResponse(
        _sse(request),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )


# --------------------------------------------------------------------------- artifacts
#
# SVG drawings, Markdown/JSON reports and BOM CSVs are generated by the agent tools
# (render_drawing / export_report) or by POST /artifacts/render and kept in the in-process
# ResultStore; the tool results and the UI only carry their download paths.


class RenderRequest(BaseModel):
    design: Design
    width_px: int = Field(default=800, ge=200, le=4000)


@app.post("/artifacts/render")
def render_artifact(request: RenderRequest) -> dict[str, object]:
    """Render a side view for any design (so the UI can draw candidates without the model)."""
    return store_drawing(request.design, width_px=request.width_px)


@app.get("/artifacts/{artifact_id}.{ext}")
def get_artifact(artifact_id: str, ext: str) -> Response:
    if ext not in MEDIA_TYPES:
        raise HTTPException(status_code=404, detail=f"unsupported artifact type {ext!r}")
    art = DEFAULT_STORE.get(f"{artifact_id}.{ext}")
    if art is None:
        raise HTTPException(status_code=404, detail=f"no artifact {artifact_id}.{ext}")
    disposition = "inline" if ext == "svg" else "attachment"
    return Response(
        content=art.content,
        media_type=art.media_type,
        headers={
            "Content-Disposition": f'{disposition}; filename="{art.key}"',
            "Cache-Control": "no-store",
        },
    )
