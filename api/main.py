"""FastAPI entry point. POST /design streams agent progress as server-sent events."""

from __future__ import annotations

import os
from collections.abc import AsyncIterator

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import Response, StreamingResponse
from pydantic import BaseModel, Field

from api.aero import router as aero_router
from api.manufacturing import router as manufacturing_router
from api.workbench import router as workbench_router
from rocketwright import __version__
from rocketwright.agent.design_package import design_package
from rocketwright.agent.loop import run_design_loop
from rocketwright.agent.store import DEFAULT_STORE, MEDIA_TYPES, store_drawing
from rocketwright.agent.tools import DISPERSION_MAX_N
from rocketwright.build import Build
from rocketwright.schema import AmateurDesign, BottleDesign, Design, DesignAdapter, Env, Requirement
from rocketwright.summary import design_summary, design_summary_from_build

CORS_ORIGINS = ["http://localhost:3000", "http://127.0.0.1:3000"]

app = FastAPI(title="RocketWright", version=__version__)
app.include_router(workbench_router)
app.include_router(manufacturing_router)
app.include_router(aero_router)
app.add_middleware(
    CORSMiddleware,
    allow_origins=CORS_ORIGINS,
    allow_methods=["*"],
    allow_headers=["*"],
)


class DesignRequest(BaseModel):
    text: str = Field(min_length=1, max_length=4000)
    seed: int | None = None
    env: Env | None = None


@app.get("/")
def root() -> dict[str, str]:
    """Orientation for anyone who opens the API port in a browser: the UI lives elsewhere."""
    return {
        "name": "RocketWright API",
        "version": __version__,
        "ui": "run `cd web && npm run dev` and open http://localhost:3000 (Node >= 18.18)",
        "docs": "/docs",
        "health": "/health",
        "design": "POST /design {text, seed?, env?} -> text/event-stream",
    }


@app.get("/health")
def health() -> dict[str, str]:
    return {"status": "ok", "version": __version__}


async def _sse(request: DesignRequest) -> AsyncIterator[str]:
    # `run_design_loop` is looked up at call time so tests can monkeypatch it on this module.
    async for event in run_design_loop(request.text, seed=request.seed, env=request.env):
        yield f"event: {event.type}\ndata: {event.model_dump_json()}\n\n"


@app.post("/design")
async def design(request: DesignRequest) -> StreamingResponse:
    if os.getenv("ROCKETWRIGHT_ENABLE_CLOUD_DESIGN") != "1":
        raise HTTPException(423, "課金APIの設計実行は無効です。ローカル試験を利用してください。")
    return StreamingResponse(
        _sse(request),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )


# --------------------------------------------------------------------------- artifacts
#
# SVG drawings, Markdown/JSON reports and BOM CSVs are generated by the agent tools
# (render_drawing / export_report) or by POST /artifacts/render and kept in the in-process
# ResultStore; the tool results and the UI only carry their download paths.


class RenderRequest(BaseModel):
    design: Design
    width_px: int = Field(default=800, ge=200, le=4000)


@app.post("/artifacts/render")
def render_artifact(request: RenderRequest) -> dict[str, object]:
    """Render a side view for any design (so the UI can draw candidates without the model)."""
    return store_drawing(request.design, width_px=request.width_px)


class SummaryRequest(BaseModel):
    design: Design
    requirement: Requirement | None = None
    build: Build | None = None  # when given, cost/BOM come from the parts bill (summary.py)
    width_px: int | None = Field(default=None, ge=200, le=4000)


@app.post("/artifacts/summary")
def summary_artifact(request: SummaryRequest) -> dict[str, object]:
    """Cost breakdown, BOM, mass budget, dimensions and a stored side view for one design."""
    design = request.design
    try:
        if request.build is not None:
            out = design_summary_from_build(request.build, requirement=request.requirement)
            design = DesignAdapter.validate_python(out["design"])
        else:
            out = design_summary(design, request.requirement)
    except (KeyError, ValueError) as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    drawing = store_drawing(design, width_px=request.width_px or 800)
    out["drawing"] = {"id": drawing["id"], "url": drawing["download"]["svg"]}
    return out


class PackageRequest(BaseModel):
    design: Design
    build: Build | None = None  # when given, the bill and the simulation are the parts build's
    requirement: Requirement | None = None
    env: Env | None = None
    seed: int | None = None  # dispersion seed and size, so a run of the agent can be repeated
    n: int | None = Field(default=None, ge=1, le=DISPERSION_MAX_N)


@app.post("/artifacts/package")
def package_artifact(request: PackageRequest) -> dict[str, object]:
    """Production files of one design: everything it can support, and what it cannot."""
    if not isinstance(request.design, AmateurDesign | BottleDesign):
        raise HTTPException(422, "製作データはボトルとアマチュアの案だけに出します")
    try:
        return design_package(
            request.design,
            build=request.build,
            requirement=request.requirement,
            env=request.env,
            seed=request.seed,
            n=request.n,
        )
    except (KeyError, ValueError) as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc


@app.get("/artifacts/{artifact_id}.{ext}")
def get_artifact(artifact_id: str, ext: str) -> Response:
    if ext not in MEDIA_TYPES:
        raise HTTPException(status_code=404, detail=f"unsupported artifact type {ext!r}")
    art = DEFAULT_STORE.get(f"{artifact_id}.{ext}")
    if art is None:
        raise HTTPException(status_code=404, detail=f"no artifact {artifact_id}.{ext}")
    disposition = "inline" if ext == "svg" else "attachment"
    return Response(
        content=art.content,
        media_type=art.media_type,
        headers={
            "Content-Disposition": f'{disposition}; filename="{art.key}"',
            "Cache-Control": "no-store",
        },
    )
