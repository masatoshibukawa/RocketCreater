"""Ordered bench assembly actions for the saved geometry and component options."""

from dataclasses import dataclass

from rocketwright.agent.project_drawing import mm


@dataclass(frozen=True)
class Procedure:
    actions: tuple[tuple[str, str], ...]
    proceed: str
    stop: str
    record: str


def assembly_procedures(spec, cad):
    g = spec.geometry
    inner = mm(g.body_diameter_mm + 2 * g.radial_clearance_mm)
    diameter = mm(g.body_diameter_mm)
    payload_g = mm(spec.design.payload_mass_kg * 1000)
    printed_parts = "ノーズとフィン" if cad["include_fins"] else "ノーズ"
    fin = cad["fin"]
    fit_before = "フィンを付ける前" if cad["include_fins"] else "ノーズを仮合わせする前"
    slots = f"軸方向 {mm(fin['slot_height'])} mm、径方向 {mm(fin['slot_width'])} mm"
    parts = (
        f"B01 ボトル、N01 ノーズ、F01 フィン {g.fin_count} 枚、J01 試着リング"
        if cad["include_fins"]
        else "B01 ボトル、N01 ノーズ、J01 試着リング"
    )
    procedures = {
        "parts": Procedure(
            (
                (
                    "版をそろえる",
                    f"部品表・設計図・印刷データの版を照合する。机に並べる部品は {parts}。",
                ),
                (
                    "基準を決める",
                    "空のボトルを横向きに置く。設計図のノズル端を0 mmとし、ノーズ側に向けて測る。",
                ),
                (
                    "胴径を測る",
                    f"取付予定部の円筒部を直交する2方向で測り、胴径 {diameter} mmと比べる。",
                ),
            ),
            "部品数と版がそろい、どの面を0 mmとするか確認できたら仕上げに進む。",
            "版違い、欠品、ボトルの傷・へこみ、または測定基準が不明な場合は部品を照合し直す。",
            "ボトルの識別名、測った位置、胴径2方向（mm）",
        ),
        "finish": Procedure(
            (
                (
                    "ブリムを外す",
                    "冷えた印刷部品の周囲からブリムを外し、ノーズ入口とリング内周に残りがないかを見る。",
                ),
                (
                    "接触面を確認",
                    "取付座とノーズ入口を目視し、反り、割れ、層の浮き、突出した樹脂を探す。",
                ),
                (
                    "固定材を試す" if cad["include_fins"] else "治具を確かめる",
                    "機体に付ける前に、固定材を設計図F01のS1・S2に一つずつ通して抜く。"
                    f"スロット公称値は{slots}。"
                    if cad["include_fins"]
                    else "試着リングの内周に指が掛かる段差や割れがないか確認する。",
                ),
            ),
            "接触面に反りやバリがなく、使用する固定材の通過を確認できたら試着に進む。"
            if cad["include_fins"]
            else "ノーズ入口とリング内周に反りやバリが見当たらなければ試着に進む。",
            "穴が塞がる、部品が反る、層が割れる場合は部品を外して記録し、形状や印刷条件を見直す。",
            "部品ID、仕上げ後の外観、固定材の通過の可否（該当時）",
        ),
        "ring_fit": Procedure(
            (
                (
                    "口側から入れる",
                    f"{fit_before}に、J01をボトルの口側から通し、胴の円筒部に軽く案内する。",
                ),
                (
                    "入り具合を見る",
                    f"リング内径 {inner} mmを基準に、"
                    "引っ掛かる場所、浮き、がたつきの有無を記録する。",
                ),
                (
                    "外して保管する",
                    "リングを来た方向へ戻して取り外す。実測値と観察結果をノーズの仮合わせに引き継ぐ。",
                ),
            ),
            "入り具合と取外しを確認できたら、同じボトルで次の工程に進む。",
            "円筒部まで届かない、押すと胴がへこむ、偏ってがたつく場合は中断し、ボトルと内径を測り直す。",
            "胴径（mm） A ____ / B ____　リング内径 ____\n引っ掛かりの位置と取外し結果を記録する。",
        ),
        "nose_fit": Procedure(
            (
                (
                    "入口と軸を合わせる",
                    f"N01の開口をボトル側へ向け、内径 {inner} mmの嵌合部をボトルの軸に合わせる。",
                ),
                (
                    "基部位置を読む",
                    "傾きに注意して軽く差し込み、ノズル端からノーズ基部までを測る。"
                    f"公称 {mm(g.nose_base_mm)} mm。",
                ),
                (
                    "抜いて確認する",
                    "差し込んだ経路に沿って戻し、入口とボトルの接触面に擦れや割れがないか確認する。",
                ),
            ),
            "傾き・浮きがなく、軽く外せることと、基部位置の実測を記録できたら次へ進む。",
            "途中で止まる、片側だけ浮く、軟質キャップの適合が不明な場合は仮合わせを止めて寸法を照合する。",
            "基部位置 ____ mm　はめ込みと取外しの結果、入口と胴の傷の有無",
        ),
        "recovery": Procedure(
            (
                ("搭載物を量る", f"設計入力 {payload_g} gと、使用する搭載物の実測を照合する。"),
                (
                    "通り道を見る",
                    "回収傘・索・搭載物の保持位置と取出し経路を机上で確認する。部品同士の絡み、引っ掛かりを観察する。"
                    if spec.design.has_parachute
                    else "ノーズを仮合わせし、搭載物の置き場所と取出し経路を机上で確認する。",
                ),
                (
                    "保留点を残す",
                    "保持部、索の固定点、開傘手順を現物で決める項目として記録する。"
                    if spec.design.has_parachute
                    else "搭載物の保持方法と、この版の回収方法を決めるために必要な確認を記録する。",
                ),
            ),
            "搭載物の質量と、取付・取出しのどこまで確認したかが記録できたら、測定へ進む。",
            "搭載物が動く、ノーズが閉まらない、取出し経路が干渉する場合は配置と保持を見直す。",
            "搭載物の実測（g）、保持・取出しの観察、保留項目",
        ),
        "measure": Procedure(
            (
                (
                    "印刷部品を量る",
                    f"機体に使う{printed_parts}の質量を記録する。試着リングの質量は治具として別に記録する。",
                ),
                (
                    "機体を測る",
                    f"全長をノズル端から測る。公称 {mm(g.overall_mm)} mm。"
                    "水なし・搭載物あり／なしなど測定条件を記録する。",
                ),
                (
                    "重心を記録する",
                    "水平に保てる支持具で釣り合う位置を探し、支持点の中心をノズル端から測る。",
                ),
                (
                    "設計に戻す",
                    "「寸法・質量を編集」で印刷部品の実測合計と変更する寸法を入力し、新しい版を保存・再解析する。",
                ),
            ),
            "実測値、測定条件、保留点がそろい、更新が必要な項目を次の版へ渡せる。",
            "部品のずれ・傷や測定のばらつきがあれば、仮組みを戻して該当工程を確認する。",
            "印刷部品合計 ____ g　全長 ____ mm　重心位置 ____ mm\n搭載物と水の有無を併記する。",
        ),
    }
    procedures["fin_mount"] = (
        Procedure(
            (
                (
                    "後端をそろえる",
                    f"設計図の0 mmから {mm(g.fin_tail_inset_mm)} mmを測り、"
                    "翼後端を合わせる位置を仮マークする。",
                ),
                (
                    "等間隔に目印を置く",
                    f"予定位置に紙帯を一周させ、重なる点までを {g.fin_count} 等分する。"
                    f"後面図の {mm(360 / g.fin_count)}°を参照する。",
                ),
                (
                    "一枚ずつ仮置きする",
                    "翼後端を同じ線に、取付座を円筒面に合わせる。取り外せるテープで机上確認中の位置を保つ。",
                ),
                (
                    "横と後ろから見直す",
                    "横から後端のずれと傾きを、後ろから等間隔を確認する。固定材の経路と保持は現物で確認する。",
                ),
            ),
            "全ての後端がそろい、取付座の浮き・ねじれ・がたつきが見当たらなければノーズへ進む。",
            "押さえ続けないと座が浮く、翼が傾く、ボトルがへこむ場合は仮固定を外して位置と寸法を見直す。",
            "翼後端（mm） "
            + " / ".join(f"{i} ____" for i in range(1, g.fin_count + 1))
            + "\n等配、浮き、ねじれの有無を併記する。",
        )
        if cad["include_fins"]
        else Procedure(
            (("工程を飛ばす", "この版はフィンなし。試着リングを外し、ノーズの仮合わせに進む。"),),
            "ノーズの仮合わせへ進む。",
            "設計図と手元の部品構成が異なる場合は、採用版と部品表を照合する。",
            "部品表のフィン欄が該当なしであること",
        )
    )
    return procedures
